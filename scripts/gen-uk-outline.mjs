// DEV-ONLY throwaway. Not imported by the app; safe to delete after running.
// Derives an accurate Great Britain silhouette + Brighton/London pins through ONE
// projection so outline and pins share the same viewBox space, and writes the
// static result to src/data/ukOutline.ts (the only artifact that ships).
//   npm i -D d3-geo topojson-client world-atlas
//   node scripts/gen-uk-outline.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { geoMercator, geoPath, geoArea } from 'd3-geo';
import { feature } from 'topojson-client';

const W = 360, H = 560, PAD = 14;

const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json', 'utf8'));
const uk = feature(topo, topo.objects.countries).features.find(
  (f) => f.properties.name === 'United Kingdom' || f.id === '826'
);

// The UK feature is a MultiPolygon; the largest polygon by area is the GB mainland
// (England + Wales + Scotland). Drops Northern Ireland + the small isles.
const gb = uk.geometry.coordinates
  .map((rings) => ({ type: 'Feature', geometry: { type: 'Polygon', coordinates: rings } }))
  .sort((a, b) => geoArea(b) - geoArea(a))[0];

const projection = geoMercator().fitExtent([[PAD, PAD], [W - PAD, H - PAD]], gb);
const round = (s) => s.replace(/-?\d+\.\d+/g, (m) => (+m).toFixed(1));
const pin = ([lng, lat]) => projection([lng, lat]).map((n) => +n.toFixed(1)); // d3 wants [lng, lat]

const d = round(geoPath(projection)(gb));
const bri = pin([-0.145, 50.822]);
const lon = pin([-0.106, 51.533]);

const ts = `// AUTO-GENERATED by scripts/gen-uk-outline.mjs — do not edit by hand.
// Accurate Great Britain silhouette + city pins (world-atlas 50m, geoMercator fit).
// Static strings only: zero runtime map dependencies ship to the client.
export const UK_VIEWBOX = '0 0 ${W} ${H}';

export const UK_OUTLINE_D =
  '${d}';

export const UK_PINS: Record<'brighton' | 'london', { x: number; y: number }> = {
  brighton: { x: ${bri[0]}, y: ${bri[1]} },
  london: { x: ${lon[0]}, y: ${lon[1]} },
};
`;

writeFileSync('src/data/ukOutline.ts', ts);
console.log('wrote src/data/ukOutline.ts');
console.log('viewBox 0 0', W, H, '| path bytes:', d.length, '| brighton', bri, '| london', lon);
